package org.jackhuang.hmcl.server;

import com.google.gson.annotations.SerializedName;
import org.jackhuang.hmcl.util.gson.JsonUtils;
import org.jetbrains.annotations.NotNullByDefault;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/// Stores HMCL-owned server state next to a server jar without relying on server.properties.
@NotNullByDefault
public final class ServerConfigManager {
    /// HMCL state file kept inside each server directory.
    private static final String STATE_FILE = ".hmcl-server.json";

    /// Bundled default server.properties used before the first server start.
    private static final String DEFAULT_PROPERTIES = "/assets/server/server.properties";

    private ServerConfigManager() {
    }

    /// Persistent state stored in [STATE_FILE].
    public record State(boolean started) {
    }

    /// Returns whether the server has been started at least once.
    public static boolean hasStarted(Path directory) {
        Path file = directory.resolve(STATE_FILE);
        if (!Files.isRegularFile(file)) {
            return false;
        }
        try {
            State state = JsonUtils.fromJsonFile(file, State.class);
            return state != null && state.started();
        } catch (Exception e) {
            return false;
        }
    }

    /// Marks the server as started.
    public static void markStarted(Path directory) {
        try {
            Files.writeString(directory.resolve(STATE_FILE),
                    JsonUtils.GSON.toJson(new State(true)), StandardCharsets.UTF_8);
        } catch (IOException ignored) {
        }
    }

    /// Returns whether a real server.properties exists.
    public static boolean hasProperties(Path directory) {
        return Files.isRegularFile(directory.resolve("server.properties"));
    }

    /// Creates server.properties from the bundled template when it does not exist yet.
    public static void createDefaultProperties(Path directory) throws IOException {
        Path target = directory.resolve("server.properties");
        if (Files.isRegularFile(target)) {
            return;
        }

        try (InputStream in = ServerConfigManager.class.getResourceAsStream(DEFAULT_PROPERTIES)) {
            if (in != null) {
                Files.copy(in, target);
            } else {
                Files.writeString(target, "# Generated by HMCL\n", StandardCharsets.UTF_8);
            }
        }
    }
}
